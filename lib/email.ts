import "server-only";
import { buildRedirectExport } from "./redirect-export";
import { sendEmail } from "./email-provider";

export type DigestLink = { domain: string; cited_url: string; suggested_redirect: string | null; audit_id: string };

function escapeHtml(value: string): string {
  return value.replace(/[&<>"']/g, (character) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[character]!);
}

export function renderWeeklyDigest(links: DigestLink[], appOrigin?: string): { subject: string; html: string; text: string } {
  const origin = appOrigin && /^https:\/\/[^/]+$/i.test(appOrigin) ? appOrigin : undefined;
  const rows = links.map((link) => {
    const rule = link.suggested_redirect
      ? buildRedirectExport(link.domain, [{ cited_url: link.cited_url, http_status: 404, suggested_redirect: link.suggested_redirect }], "htaccess").split("\n").slice(1).join("\n")
      : "No verified replacement is available yet.";
    const reportUrl = origin ? `${origin}/audit/${encodeURIComponent(link.audit_id)}` : null;
    return { ...link, rule: rule || "No verified replacement is available yet.", reportUrl };
  });
  const subject = `Citemend weekly alert: ${rows.length} new 404 citation${rows.length === 1 ? "" : "s"}`;
  const html = `<main style="font-family:Arial,sans-serif;max-width:680px;margin:auto;color:#183327"><h1>New 404 citations found</h1><p>Your weekly AI citation audit confirmed ${rows.length} new broken link${rows.length === 1 ? "" : "s"}. Each redirect below is suggested only when its destination was verified.</p>${rows.map((row) => `<section style="border-top:1px solid #dce6d1;padding:16px 0"><h2 style="font-size:18px">${escapeHtml(row.domain)}</h2><p>Broken URL: <a href="${escapeHtml(row.cited_url)}">${escapeHtml(row.cited_url)}</a></p><p>301 fix:</p><pre style="white-space:pre-wrap;overflow-wrap:anywhere;background:#f7f9f3;padding:12px">${escapeHtml(row.rule)}</pre>${row.reportUrl ? `<p><a href="${escapeHtml(row.reportUrl)}">View audit report</a></p>` : ""}</section>`).join("")}<p>Generated by Citemend AI weekly monitoring.</p></main>`;
  const text = [`${subject}\n`, "The weekly AI citation audit confirmed these new 404 links.\n", ...rows.map((row) => `${row.domain}\nBroken URL: ${row.cited_url}\n301 fix: ${row.rule}${row.reportUrl ? `\nReport: ${row.reportUrl}` : ""}\n`)].join("\n");
  return { subject, html, text };
}

export async function sendWeeklyDigest(userId: string, digestId: string, links: DigestLink[]): Promise<string> {
  if (!process.env.BREVO_API_KEY?.trim() && !process.env.RESEND_API_KEY?.trim()) throw new Error("Email delivery is not configured.");
  if (!links.length) throw new Error("A weekly digest requires new broken links.");
  const { clerkClient } = await import("@clerk/nextjs/server");
  const user = await (await clerkClient()).users.getUser(userId);
  const recipient = user.emailAddresses.find((email) => email.id === user.primaryEmailAddressId)?.emailAddress;
  if (!recipient) throw new Error("The account has no primary email address.");
  const message = renderWeeklyDigest(links, process.env.NEXT_PUBLIC_APP_URL?.replace(/\/$/, ""));
  const delivery = await sendEmail({
    from: process.env.EMAIL_FROM?.trim() || process.env.RESEND_FROM_EMAIL?.trim(),
    to: recipient,
    subject: message.subject,
    html: message.html,
    text: message.text,
    idempotencyKey: `weekly-${digestId}`,
  });
  return delivery.id;
}
